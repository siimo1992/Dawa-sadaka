// Find nearest Wilaya based on latitude and longitude
export function findNearestWilaya(lat: number, lng: number): WilayaInfo {
  let nearest = ALGERIA_WILAYAS[0];
  let minDistance = Infinity;

  for (const w of ALGERIA_WILAYAS) {
    const d = getDistanceFromLatLonInKm(lat, lng, w.lat, w.lng);
    if (d < minDistance) {
      minDistance = d;
      nearest = w;
    }
  }

  return {
    ...nearest,
    distanceFromInSalahKm: getDistanceFromLatLonInKm(
      nearest.lat,
      nearest.lng,
      IN_SALAH_COORDS.lat,
      IN_SALAH_COORDS.lng
    ),
  };
}

export function getWilayaById(idOrCode: string | number): WilayaInfo | undefined {
  if (typeof idOrCode === 'number') {
    return ALGERIA_WILAYAS.find((w) => w.code === idOrCode);
  }
  return ALGERIA_WILAYAS.find((w) => w.id === idOrCode || String(w.code) === idOrCode);
}
